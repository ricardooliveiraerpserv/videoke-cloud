def dictionary_genre(name: str) -> str | None:
    """Estilo do artista pelo dicionário: overrides primeiro, senão o padrão do
    bloco (sertanejo/pagode). None se o artista não é conhecido."""
    from .text import normalize
    n = normalize(prefer_known_spelling(name))
    overrides = {normalize(k): v for k, v in GENRE_OVERRIDES.items()}
    if n in overrides:
        return overrides[n]
    positions = {normalize(k): i for i, k in enumerate(KNOWN_ARTISTS)}
    if n not in positions:
        return None
    return "Pagode" if positions[n] >= KNOWN_ARTISTS.index("Molejo") else "Sertanejo"


def prefer_known_spelling(name: str) -> str:
    """Se o nome (ou a variante '&'↔'e') já está no dicionário, usa a grafia
    do dicionário — evita duplicar 'Chitãozinho & Xororó' × 'Chitãozinho e Xororó'
    quando o nome vem da web."""
    from .text import normalize
    name = canonical_artist(name)
    by_norm = {normalize(k): k for k in KNOWN_ARTISTS}
    n = normalize(name)
    if n in by_norm:
        return by_norm[n]
    alt = n.replace(" & ", " e ") if " & " in n else n.replace(" e ", " & ")
    return by_norm.get(alt, name)
