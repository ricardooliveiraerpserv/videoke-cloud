"""Ports (interfaces) de persistência — Repository Pattern + DIP.

Os casos de uso dependem só destes Protocols. As implementações concretas
(SQLAlchemy/FTS5) vivem em infrastructure e são injetadas via DI.
"""
from __future__ import annotations

from typing import Protocol

from .catalog.entities import Artist, Channel, MediaFile, Song, SongRow


class ISongRepository(Protocol):
    def get(self, song_id: str) -> Song | None: ...
    def get_many(self, ids: list[str]) -> list[Song]: ...
    def by_song_key(self, key: str) -> Song | None: ...
    def add(self, song: Song) -> None: ...
    def update(self, song: Song) -> None: ...
    def count(self) -> int: ...
    # projeção leve p/ a lista (sem carregar o grafo de versões/artistas)
    def browse_rows(self, limit: int, offset: int) -> list[SongRow]: ...


class IMediaRepository(Protocol):
    def add(self, media: MediaFile) -> None: ...
    def by_hash(self, sha256: str) -> MediaFile | None: ...
    def mark_missing(self, ids: list[str]) -> None: ...
    def path_of(self, media_file_id: str) -> str | None: ...
    def all_paths(self) -> list[tuple[str, str]]: ...


class IArtistRepository(Protocol):
    def get_or_create(self, name: str) -> Artist: ...


class IChannelRepository(Protocol):
    def get_or_create(self, name: str, external_id: str | None = None) -> Channel: ...


class ISearchIndex(Protocol):
    """Busca full-text (FTS5). Retorna ids de músicas na ordem de relevância."""
    def search(self, query: str, limit: int, after: str | None) -> list[str]: ...
    def count(self, query: str) -> int: ...


class IPresetRepository(Protocol):
    def get(self, song_id: str, user_id: str | None) -> tuple[int, int] | None: ...  # (pitch, tempo)
    def save(self, song_id: str, pitch: int, tempo: int, user_id: str | None) -> None: ...


class IUnitOfWork(Protocol):
    songs: ISongRepository
    media: IMediaRepository
    artists: IArtistRepository
    channels: IChannelRepository
    search: ISearchIndex
    presets: IPresetRepository

    def __enter__(self) -> "IUnitOfWork": ...
    def __exit__(self, *exc) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
